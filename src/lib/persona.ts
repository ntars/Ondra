/**
 * 她的身份：名字的兜底与在场状态。
 *
 * ## 名字现在从哪来
 *
 * 2.3.1 起人名来自**人设包**：宿主 `GET /api/personas` 给出
 * `display_name`（例如「哦鲸鲸（鲸鲸 / 蓝色大肥鱼 / 鲸鱼娘）」），标题栏取
 * 其中最短的那个包名。这个常量只剩下一个职责：**宿主没起来时**标题栏
 * 不能空着。连接失败页与首帧都在这条路上，它们读不到人设包。
 *
 * 名字取「空谷」而不是某个角色名：产品名是唯一在「还没有人设」时也成立
 * 的名字。写某个角色名，换包之后就成了错的名字。
 *
 * ## 在场状态三档，全部从真实链路推导
 *
 * | 状态 | 判据 | 读作 |
 * | --- | --- | --- |
 * | 在想 | 正在生成 **且** 链路通 | 「在想」 |
 * | 在线 | 有网 + 宿主活着 + 至少接了一个模型 | 「在线」 |
 * | 离线 | 上面任一条不成立 | 「离线」 |
 *
 * 上一版只有两档，且「在线」从不检查任何东西——没配模型、宿主挂了、
 * 机器断网，它照样写「在线」。那个绿点唯一的作用是让人不再怀疑哪里坏了。
 * 判据搬到 `lib/usePersona.ts` 的 `usePresence`，常量只留文案。
 */

/** 在场状态。 */
export type Presence = 'online' | 'thinking' | 'offline'

/** 兜底身份。只在宿主没起来时用到。 */
export const PERSONA = Object.freeze({
  /** 名字。连接失败页、骨架页、以及人设清单读不到时用它。 */
  name: '空谷',
})

/**
 * 状态词。
 *
 * @param presence 在场状态。
 * @returns 一个词，用于界面与读屏。
 */
export function presenceLabel(presence: Presence): string {
  if (presence === 'thinking') return '在想'
  return presence === 'online' ? '在线' : '离线'
}
