/**
 * 她的身份：名字与在场状态。
 *
 * ## 为什么名字写在代码里
 *
 * 本版没有「人设包」这条数据链：宿主不返回人格名，配置里也没有这个字段。
 * 与其猜一个（读会话标题？读模型名？），不如显式写一处常量——它是**已知
 * 的唯一真源**，将来人设链打通时只改这一行，界面不动。
 *
 * 名字取「空谷」：它是产品名，也是她在界面里的自称。不写某个角色名，
 * 是因为换人设包之后那个名字就不对了，而这一版还没有换包的入口。
 *
 * ## 在场状态只有两档，而且必须从真实状态推导
 *
 * | 状态 | 判据 | 读作 |
 * | --- | --- | --- |
 * | 在想 | 正在生成（`busy`） | 「在想」 |
 * | 在线 | 其余时刻 | 「在线」 |
 *
 * 上一版有第三档「等你回答」（有待处理的交互请求）。本版的宿主不提供
 * 这个信号——没有「待确认」的队列可查——所以这里不造一个假的第三档：
 * 界面上写着「等你回答」而实际没有在等，是比缺一档更坏的缺陷。
 */

/** 在场状态。 */
export type Presence = 'online' | 'thinking'

/** 她的名字与头像用的字。 */
export const PERSONA = Object.freeze({
  /** 名字。侧栏身份行、无障碍标签用它。 */
  name: '空谷',
})

/**
 * 状态词。
 *
 * @param presence 在场状态。
 * @returns 一个词，用于 tooltip 与读屏。
 */
export function presenceLabel(presence: Presence): string {
  return presence === 'thinking' ? '在想' : '在线'
}
