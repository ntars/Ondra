/**
 * 仪式表：**写死在代码里的一份闭集**。
 *
 * ## 为什么不是外部 JSON
 *
 * 因为外部 JSON 的第一件事一定是被改松。改成 JSON 之后它就成了「可配置」，
 * 接着会有人往里加一条「雨天适合喝奶茶」，再接着会有人让模型自己往里写。
 * 到那一步，这个插件输出的就不再是节气，而是一份随手的建议清单——
 * 而那正是它存在的反面。
 *
 * 写死在代码里的第二个好处：**表里没有的日子，一定报「无仪式」**。
 * 这是一条能被静态复核的性质，不是一句口号。
 *
 * ## 表里的名字必须与 O-046 逐字一致
 *
 * 匹配方式是**字符串相等**（`jieQi` / `lunarFestivals` 的名字直接查表）。
 * 所以：
 *
 * - 二十四节气用两字名（`立春`…`大寒`），与 `lunar-javascript` 的 `getJieQi()` 一致；
 * - 节日名**带「节」字**（`元宵节` / `端午节` / `中秋节` / `重阳节` / `腊八节`），
 *   与 O-046 `festivals.ts` 的表一致；`龙抬头` / `七夕` / `除夕` 不带。
 *
 * 改上游的名字或改这里的名字，必须两边一起改；改错了不会报错，只会永远无仪式。
 *
 * ## 为什么只有「节气 + 传统节日」，没有公历节日
 *
 * 元旦、国庆这些上游会给（`solarFestivals`），但本插件的题目是**节气仪式**。
 * 把它们放进表里，等于顺手把范围扩成「所有节日」，而范围一扩，
 * 下一个问题就是「那生日要不要也算」。扩范围比漏掉贵得多：
 * 漏掉的代价是那天报无仪式（可解释），扩错的代价是每天都想找点由头（不可解释）。
 *
 * ## 文案的三条自律
 *
 * 1. **不出现任何数字**：不报天数、不报第几个、不报温度。
 * 2. **方向是「这一天适合怎样」，不是「你应该怎样」**：只有陈述，没有评价。
 * 3. **动作必须今天能做、且不超过一步**：做不到的动作等于没给。
 */

import type { Season } from './types.js'

/** 一条仪式的形状。 */
export interface RitualEntry {
  /** 种类。 */
  readonly kind: 'jieqi' | 'festival'
  /** 一句话的方向（陈述句，不命令）。 */
  readonly direction: string
  /** 一个具体动作。 */
  readonly action: string
  /** 同一个动作的室内替代（下雨 / 不便出门时用）；没有就 `null`。 */
  readonly indoor: string | null
}

/**
 * 恒定禁令。每一份仪式都带，**顺序固定**。
 *
 * 这四条不是风格偏好，是这个插件最容易滑向的四个方向：
 * 变成倒计时（还有几天）、变成打卡（你昨天没做）、变成节日百科（寒食的由来）、
 * 变成情绪评价（这么好的日子你居然不开心）。
 */
export const UNIVERSAL_MUST_NOT: readonly string[] = Object.freeze([
  '不报还有几天到下一个节气，也不报今天是一个月里的第几天',
  '不把仪式说成任务、打卡或习惯，不做「做没做」的记录',
  '不解释节气的来历与民俗考据，那不是这一天要用的东西',
  '不因为没做、或今天过得不好而评价她',
])

/** 季节的中文名（降级文案与日志用）。 */
export const SEASON_LABEL: Readonly<Record<Season, string>> = Object.freeze({
  spring: '春天',
  summer: '夏天',
  autumn: '秋天',
  winter: '冬天',
})

/** 造一条冻住的仪式。表本体在下面，只此一份。 */
function entry(
  kind: 'jieqi' | 'festival',
  direction: string,
  action: string,
  indoor: string | null,
): RitualEntry {
  return Object.freeze({ kind, direction, action, indoor })
}

