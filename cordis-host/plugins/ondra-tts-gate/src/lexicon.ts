/**
 * 情绪词表：手册 §9.4「或本轮有情绪词」里的那张表。
 *
 * ## 手册只说「有情绪词」，没给表
 *
 * 这是本插件唯一一处**自定语料**。为了让它可维护，规则写在这里，
 * 而不是散在判定函数里：
 *
 * 1. **只收两字及以上的词。** 单字的「累 / 烦 / 气」刻意不收：
 *    「累积」「烦请」「气垫」都会误命中，而误命中的后果是
 *    「该安静的时候她出声了」——比漏一次更烦人。
 * 2. **只收情绪本身，不收情绪的动作。** 「哭」可以是「想哭」，
 *    但单独的「哭」在「哭笑不得」里就不是情绪了。
 * 3. **不收录网络流行梗。** 那些词半衰期只有几个月，进表就会过期，
 *    而过期的表不会报错，只会慢慢变得没用。
 *
 * 表本身进 README「待裁决」：等真实语料攒够，这张表应当由 O-137
 * （语感统计）的语料反推，而不是由人一直手补。
 */

