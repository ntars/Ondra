/**
 * 一条合并正则。
 *
 * 40 个词线性 `indexOf` 也是可以的（文本 ≤120 字），但那样每加一个词
 * 就多一次全串扫描；合成一条正则只扫一遍，且顺序无关。
 */
const EMOTIVE_RE = new RegExp(EMOTIVE_WORDS.join('|'))

/**
 * 这段文本里有没有情绪词。
 * @param text 已净化的文本。
 */
export function hasEmotive(text: string): boolean {
  if (text === '') return false
  return EMOTIVE_RE.test(text)
}
