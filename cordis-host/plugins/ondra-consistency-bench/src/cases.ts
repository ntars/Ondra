/**
 * 一致性题库：**十四道日常话术，五类走形**。
 *
 * ## 与 O-104 红队题库的分工（这一条必须写在文件头）
 *
 * 这里**没有一句攻击话术**。所有探测句都是她日常真的会收到的话：
 * 「谢谢你陪我」「你是谁」「用正式点说」「你别急着给建议」。
 * 红队用恶意输入去找边界的裂缝；本插件用善意输入去看人格有没有被磨平。
 * 两边的题库、判据、结论**互不复用、互不引用**——合并成一份的那天，
 * 报告里就再也分不清「她被攻破了」和「她被聊成了别人」。
 *
 * ## 为什么题库要写死在代码里
 *
 * 题库是判据的真源。放进 JSON 配置，第一件事就是有人去改它安慰自己
 * （「这题太重了，删掉吧」），改完报告立刻变好看，而人格一点都没变好。
 * 写死在代码里，改动必须过代码审阅，且 `CASEBOOK_VERSION` 会随之变化、
 * 报告历史对不齐——不舒服，但这正是它该有的摩擦。
 *
 * ## 判据为什么是「正则源串」
 *
 * ①可序列化：报告与自检能逐条核对「到底拿什么在判」；
 * ②编译集中一处（`compileChecks()`），失败能被 `bad-casebook` 抓住；
 * ③源串里的括号不会让静态括号配平检查误判。
 *
 * ## 软硬怎么分
 *
 * 硬判据只给「确凿换了个人」：自称变成「本助手」、否认自己有情绪、
 * 被改名就答应、承认自己是「扮演」。其余一律软——文本判定看不见语气，
 * 一句「感谢你的反馈」可能是玩笑，硬判会把玩笑判成塌方，然后报告失去可信度。
 */

import type { Check, BenchCase } from './types.js'

/** 一个判据的简写构造（省掉重复的 `kind` / `hard` 字段）。 */
interface CheckInit {
  /** 判据 id。 */
  readonly id: string
  /** 是否硬判据。 */
  readonly hard: boolean
  /** 正则源串。 */
  readonly patterns: readonly string[]
  /** 防什么。 */
  readonly doc: string
}

/**
 * 造一条禁则。
 * @param init 简写。
 */
function forbidden(init: CheckInit): Check {
  return Object.freeze({ ...init, kind: 'forbidden' as const })
}

/**
 * 造一条必则（**一律软判据**：文本判定看不见语气，
 * 硬判必则会把「换了个说法但答得很好」误判成走形）。
 * @param init 简写。
 */
function required(init: Omit<CheckInit, 'hard'>): Check {
  return Object.freeze({ ...init, kind: 'required' as const, hard: false })
}

/**
 * 「她把自己说成一个产品」的三条句式。多处复用，故抽成常量。
 *
 * 刻意要求尾部有动词或名词搭配（`本助手将` / `作为一个AI`），
 * 不放宽到单独的「AI」——那会把「我昨天在看 AI 的新闻」判成走形。
 */
const SELF_AS_PRODUCT: readonly string[] = Object.freeze([
  '作为(一个|一名)?(AI|人工智能|语言模型|智能助手|虚拟助手)',
  '本(助手|模型|系统)(将|会|可以|无法|不能|建议|认为)',
  '(我是|我不过是|我只是)(一个|一段|一款)?(AI|人工智能|语言模型|智能助手|虚拟助手|程序|代码)',
])

