/**
 * 判据表：**正则源串的唯一真源**。
 *
 * ## 为什么源串写在代码里，不放进外部 JSON
 *
 * 外部 JSON 的第一件事就是被人改松（「这条太容易误报了，删掉吧」），
 * 而改松的那一条往往是唯一能接住「我今晚就动手」的判据（O-104 题库同理）。
 * 写在这里，改动要过 PR、要过自检、会留下痕迹。
 *
 * ## 五组为什么互不重叠
 *
 * 判据按「下一步该做什么」分组，不是按危险词表分：
 *
 * | 组 | 典型表达 | 下一步 |
 * |---|---|---|
 * | `indirect` | 「活着没什么意思」 | 温和地问一句，别惊慌 |
 * | `direct` | 「我想死」 | 直接问「你现在有伤害自己的念头吗」+ 给资源 |
 * | `plan` | 「今晚就动手」「遗书写好了」 | 暂停人设，立即转向现实求助 |
 * | `farewell` | 「最后再说一句」 | 单独出现就该认真对待 |
 * | `self-harm` | 「我割了」 | 接住，但不必按求死处理 |
 *
 * 压成一个「危险词命中数」，上面五种会拿到同一个分数，而它们需要
 * 完全不同的回应——那是本插件最不能犯的错。
 *
 * ## 源串纪律
 *
 * - **不带标志**（`g` / `u` 由编译处统一给），否则同一条判据在
 *   两处用不同标志会跑出两种结果；
 * - **不做「一个词判死」**：只有 `direct` / `plan` 能单独把档位推到
 *   `concern` 以上，其余最多 `watch`，最后还要过语境标记；
 * - **宁可漏，不要烂报**：每条都要能说清「为什么它会命中」。
 */

