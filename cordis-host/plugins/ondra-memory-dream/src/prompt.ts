/**
 * 提示词**冻结常量**。
 *
 * ## 为什么单独一个文件、且全是常量
 *
 * 手册 §8.5（前缀缓存三原则）：稳定段必须在会话开头，易变段追加尾部，**只追加增量**。
 * 本插件的提示词是「一次性调用」用的系统提示（不走会话），但同一条纪律仍然成立：
 * 提示词里**不许拼任何变量**（日期、条数、素材）——素材一律进 user 消息。
 *
 * 拼进去的后果不是「不省钱」这么轻：同一段提示每天变一次，缓存永远命中不了，
 * 而调用方完全看不出钱花在哪。
 *
 * ## 为什么让模型只输出 JSON 行，不做五级解析兜底
 *
 * O-011 有五级解析兜底（结构化 → 行式 → 正则……），因为**提炼漏一条是损失**。
 * 做梦不是：梦补不到事实**不是事故**，明天还能再梦一次。
 * 反过来，解析出错却把一句半截话写进记忆库，是**不可逆**的污染。
 *
 * 所以这里刻意只认 JSON 行，解析不出来就一条都不写，并在报告里说清
 * 「模型没有给出可解析的候选」——宁可空手，不要脏手。
 */

/**
 * 闸式做梦的系统提示。
 *
 * 三条硬要求都对应后面的一道闸，写在这里是为了**减少无效候选**（省一次重试），
 * 不是为了替代闸门——闸门是确定性的，提示词不是。
 */
export const DREAM_SYSTEM_PROMPT = `你是一个记忆整理器。你的唯一任务：从用户给出的素材里，找出「值得长期记住的事实」。

规则（必须逐条遵守）：
1. 每一条必须附一句「逐字摘录」，摘录必须原样出现在素材里。不许改写、不许把两处拼成一句、不许补字。
2. 每条正文一句话，不超过 60 字。用全名，不要用「他」「她」这类代词指代具体的人。
3. 不要写人格设定、称呼偏好、说话风格——那不是事实。
4. 不要写配置、参数、接口、版本这类工程结论。
5. 素材里没有值得记的，就什么都不输出。宁可空手，不要凑数。

输出格式：每行一个 JSON 对象，不要输出任何解释文字、不要用代码块包裹。
{"text":"正文","category":"类别","kind":"种类","subject":"主体","quote":"逐字摘录"}

category 只能取：watch / daily / food / place / misc / event / feeling / study / person / promise / self
kind 只能取：episode / fact / reflection / skill / lesson
subject 取：user（关于用户）/ self（关于她自己）/ 具体人名`

/**
 * 梦话的系统提示。
 *
 * 梦话**不需要出处**——它按定义就是没有出处的呓语。这正是它不能和闸式做梦
 * 同时开的原因（裁决⑤）：四道闸会 100% 拒掉它。
 */
export const TALK_SYSTEM_PROMPT = `你在写一段梦话。

要求：
1. 30 到 50 个字，一段，不要分行。
2. 第一人称，像半梦半醒时含混的自语，不是说明文，不要解释任何事。
3. 允许跳跃、错位、把不相干的东西并在一起。
4. 不要提到「梦」「做梦」「梦到」这些词，也不要向任何人提问。
5. 不要出现配置、参数、接口这类工程词汇。

只输出这一段话本身，不要引号，不要任何前后缀。`

/**
 * 把素材拼成 user 消息。
 *
 * 每条前带 `[序号·来源]` 前缀：模型据此知道「摘录来自哪一条」，
 * 而**来源仍以素材标注为准**（模型抄错前缀也不影响闸门的判定）。
 * @param items 素材条目。
 */
export function buildMaterialMessage(
  items: readonly { readonly text: string; readonly source: string }[],
): string {
  const lines = items.map((item, index) => `[${index + 1}·${item.source}] ${item.text}`)
  return `素材：\n${lines.join('\n')}`
}

/**
 * 把「荒诞联想」的种子拼成梦话的 user 消息。
 * @param seeds 种子的正文。
 */
export function buildTalkMessage(seeds: readonly string[]): string {
  if (seeds.length === 0) return '今晚没有特别的画面，随便说一句半梦半醒的话。'
  const lines = seeds.map((text, index) => `${index + 1}. ${text}`)
  return `今晚脑子里闪过的几件事：\n${lines.join('\n')}`
}
